class conexion
{
private	$host;
private	$database;
private	$login;
private	$password;
private	$port;
private	$sistema;
var	$obj_conec;

		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		/* Compatibilidad: en PHP 8 el método con el mismo nombre de la clase
		   dejó de ser constructor, por lo que `new conexion()` no inicializaba
		   host/usuario/clave y la conexión fallaba. Se llama explícitamente y
		   se mantiene el método original para entornos antiguos. */
		function __construct(){

			$this->conexion();

		}///FIN DEL CONSTRUCTOR

		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function conexion(){
		
			$this->host="127.0.0.1";
			$this->database="sovca_qas";
			$this->login="postgres";
			$this->password="postgres";
			$this->port="5432";
			$this->sistema="Bovinos";
			
		}///FIN DE LA FUNCTION
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function CONNECT(){
		
			if (!($Coneccion= @pg_connect("host=".$this->host." port=".$this->port." dbname=".$this->database." user=".$this->login."  password=".$this->password." "))){
				
				return false;
			}// fin del if------
			
			$this->obj_conec=$Coneccion;  	  
			return $Coneccion;
		}// fin de la funcion------
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function SQL_QUERY($sql){
		
			$rs=@pg_query($sql);
			return $rs;
		
		}// fin de la funcion------------
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function BEGIN_TRANSAC(){
			
			$rs=@pg_query("BEGIN");
			return $rs;
		
		}// fin de la funcion------------
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function COMMIT(){
			
			$rs=@pg_query("COMMIT");
			return $rs;
		
		}// fin de la funcion------------
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function ROLLBACK(){
			
			$rs=@pg_query("ROLLBACK");
			return $rs;
		
		}// fin de la funcion------------
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function DISCONECT() {
		
			@ pg_close();
		}// fin de la funcion------------
		 //---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function FREE_RESULT($rs){
		
			$rs=@pg_free_result($rs);
			return $rs;
		
		}// fin de la funcion------------
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		private function  GET_ID_SISTEMA()
		{
			$sql="select id from seguridad.segsistemas where strnombre='".$this->sistema."' ";
			$rs=$this->SQL_QUERY($sql);
			$arr=pg_fetch_array($rs);
			$id=$arr["id"];
			$this->FREE_RESULT($rs);
			return $id;
			
		}
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------
		function GET_SISTEMA(){
			
			return $this->GET_ID_SISTEMA();
		}
		//---------------------------------------------------------------------------------------------------------------
		//---------------------------------------------------------------------------------------------------------------

}// fin de la clase-----------------------------------------------------------------------------------------------------
